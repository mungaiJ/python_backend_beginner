# Report Card Printer

# Store the student's name as a string
name = 'Alice'

# Print the name and its data type
print(name, type(name))

# Store whether the person is a student as a boolean
is_student = True

# Print the boolean value and its data type
print(is_student, type(is_student))

# Store the student's age as an integer
age = 20

# Print the age and its data type
print(age, type(age))

# Store the student's score as a floating-point (decimal) number
score = 80.5

# Check if score is an integer (returns False because it's a float)
print(isinstance(score, int))

# Check if score is a float (returns True)
print(isinstance(score, float))

# Print the score and its exact data type
print(score, type(score))